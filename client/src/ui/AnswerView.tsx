import { useEffect, useRef, useState, type CSSProperties } from 'react';
import { assessmentDetails, type Assessment } from '../../../shared/answerFormat.ts';
import { findExperienceClaims } from '../../../shared/experienceClaims.ts';
import { checkAvailabilityNumbers } from '../../../shared/numericChecks.ts';
import { unverifiedSpecifics } from '../../../shared/unverifiedSpecifics.ts';
import type { AnswerGroup } from '../answers/grouping.ts';
import { firstWordTiming } from '../answers/timing.ts';
import type { AnswerCard } from '../answers/useAnswers.ts';
import type { AnswerDisplay } from '../settings.ts';

const ASSESSMENT_LABEL: Record<Assessment, string | null> = {
  none: null,
  incorrect_premise: 'Incorrect premise',
  unrecognized_term: 'Unrecognized term',
  possible_transcription_error: 'Possibly misheard',
  clarification_needed: 'Needs clarification',
  unrealistic_requirement: 'Unrealistic requirement',
  insufficient_information: 'Not enough information',
  unverified_experience: 'Unverified experience',
  off_topic: 'Off-topic',
  unverified: 'Unverified answer',
};
const MODEL_LABEL: Record<Exclude<AnswerCard['engine'], 'simulated'>, string> = {
  'groq-120b': 'GPT-OSS 120B on Groq',
  'groq-20b': 'GPT-OSS 20B on Groq',
};

const seconds = (ms: number | null) => (ms === null ? '—' : `${(ms / 1000).toFixed(2)} s`);

export function answerTextStyle(display: AnswerDisplay): CSSProperties {
  return { fontSize: `${display.fontSize}px`, lineHeight: display.lineSpacing };
}

/** Says plainly whether a person should treat the text as AI output or a canned placeholder. */
function SourceBadge({ card }: { card: AnswerCard }) {
  if (card.engine === 'simulated') {
    return (
      <span className="badge badge-simulated" data-testid="answer-source" title="Canned placeholder text for testing. No AI model was used.">
        Simulated · not AI
      </span>
    );
  }
  return (
    <span className="badge badge-ai" data-testid="answer-source" title="Generated by an AI model. Check it before you rely on it.">
      AI-generated · {MODEL_LABEL[card.engine]}
    </span>
  );
}

function CopyButton({ text }: { text: string }) {
  const [state, setState] = useState<'idle' | 'copied' | 'failed'>('idle');
  useEffect(() => {
    if (state === 'idle') return;
    const timer = setTimeout(() => setState('idle'), 2000);
    return () => clearTimeout(timer);
  }, [state]);
  const copy = () => {
    // Clipboard access needs a secure context and a user gesture; both hold for this click.
    if (!('clipboard' in navigator)) return setState('failed');
    void navigator.clipboard.writeText(text).then(
      () => setState('copied'),
      () => setState('failed'),
    );
  };
  return (
    <button type="button" onClick={copy} disabled={!text} aria-live="polite">
      {state === 'copied' ? 'Copied' : state === 'failed' ? 'Copy failed' : 'Copy answer'}
    </button>
  );
}

interface Props {
  group: AnswerGroup;
  display: AnswerDisplay;
  onCancel: (questionId: string) => void;
  onRegenerate: (card: AnswerCard, engine?: AnswerCard['engine']) => void;
  /** Focus mode: bigger question, no timing details. */
  focus?: boolean;
}

export function AnswerView({ group, display, onCancel, onRegenerate, focus = false }: Props) {
  const count = group.versions.length;
  // null follows the newest version; picking an older one pins it until a new version arrives.
  const [picked, setPicked] = useState<number | null>(null);
  const [showSmallTalk, setShowSmallTalk] = useState(false);
  const seenCount = useRef(count);
  useEffect(() => {
    if (count !== seenCount.current) setPicked(null);
    seenCount.current = count;
  }, [count]);
  const index = picked ?? count - 1;
  const card = group.versions[index] ?? group.versions[count - 1];
  if (!card) return null;
  const label = card.header ? ASSESSMENT_LABEL[card.header.assessment] : null;
  const details = label && card.header ? assessmentDetails(label, card.header, card.text) : null;
  const timing = firstWordTiming(card);
  const streaming = card.status === 'streaming';
  // A local safety net for hard rule 3: the prompt forbids invented experience, this catches slips.
  const claims = findExperienceClaims(card.text);
  // Specific settings or commands named next to an unfamiliar term may be invented.
  const numberIssues = streaming ? [] : checkAvailabilityNumbers(card.text);
  const specifics = card.header?.assessment === 'unrecognized_term' && !streaming ? unverifiedSpecifics(card.text) : [];

  // Small talk that got past the local checks: no answer card, just a line (FR-E5).
  if (card.header?.assessment === 'off_topic' && !showSmallTalk) {
    return (
      <article className="answer off-topic" data-testid="answer">
        <span className="muted">
          “{card.question}”: small talk, no answer needed.
        </span>{' '}
        <button type="button" className="link" onClick={() => setShowSmallTalk(true)}>
          Show reply
        </button>
      </article>
    );
  }

  return (
    <article
      className={`answer status-${card.status}${card.engine === 'simulated' ? ' simulated' : ' ai'}${focus ? ' focus' : ''}`}
      data-testid="answer"
    >
      <p className="answer-question">{card.question}</p>
      <div className="answer-tags">
        <SourceBadge card={card} />
        {group.askedAgainAt !== null && <span className="badge">Asked again · earlier answer shown</span>}
        {count > 1 && (
          <span className="versions" role="group" aria-label="Answer versions">
            <button type="button" className="link" disabled={index === 0} onClick={() => setPicked(index - 1)} aria-label="Previous version">
              ‹
            </button>
            <span data-testid="answer-version">
              Version {index + 1} of {count}
            </span>
            <button type="button" className="link" disabled={index === count - 1} onClick={() => setPicked(index + 1)} aria-label="Next version">
              ›
            </button>
          </span>
        )}
      </div>
      {label && (
        <div className="assessment" data-testid="assessment">
          <strong>{label}</strong>
          {details?.note && <span> · {details.note}</span>}
          {details?.clarify && <div className="clarify">Ask: “{details.clarify}”</div>}
        </div>
      )}
      {claims.length > 0 && (
        <div className="assessment experience-warning" role="note" data-testid="experience-warning">
          <strong>Claims experience you haven't verified</strong> · No resume or verified experience is loaded, so don't say this as fact: “
          {claims[0]}”
        </div>
      )}
      {numberIssues.length > 0 && (
        <div className="assessment experience-warning" role="note" data-testid="number-check">
          <strong>Check the numbers</strong> · {numberIssues.map((i) => i.message).join(' ')}
        </div>
      )}
      {specifics.length > 0 && (
        <div className="assessment experience-warning" role="note" data-testid="unverified-specifics">
          <strong>Unverified specifics</strong> · The term wasn't recognized, so these may not exist. Check before saying them: {specifics.join(', ')}
        </div>
      )}
      <div className="answer-text" data-testid="answer-text" style={answerTextStyle(display)}>
        {card.text}
        {streaming && <span className="cursor" aria-hidden="true">▍</span>}
      </div>
      {card.status === 'cancelled' && <p className="muted stopped">Stopped early{card.error ? `: ${card.error}` : '.'} The text so far is kept.</p>}
      {card.status === 'failed' && card.error && <p className="error">{card.error}</p>}
      <div className="answer-actions">
        <CopyButton text={card.text} />
        {streaming ? (
          <button type="button" onClick={() => onCancel(card.questionId)}>
            Stop answer
          </button>
        ) : (
          <>
            <button type="button" onClick={() => onRegenerate(card)} title="Keeps this answer and adds a new version">
              Regenerate
            </button>
            {card.engine === 'groq-20b' && (
              <button type="button" onClick={() => onRegenerate(card, 'groq-120b')} title="Uses the larger model for a harder question; one more request">
                Regenerate with 120B
              </button>
            )}
          </>
        )}
      </div>
      {card.truncated && (
        <p className="muted stopped" data-testid="answer-truncated">
          Cut off at the token budget for this length. Try Detailed or Regenerate.
        </p>
      )}
      {!focus && (
        <p className="answer-meta">
          {card.length} · {timing.label} {seconds(timing.ms)} · server first
          word {seconds(card.serverFirstTokenMs)} · total {seconds(card.totalMs)}
          {card.cached && ' · reused from cache, no request'}
          {card.usage &&
            ` · tokens in ${card.usage.promptTokens} / out ${card.usage.completionTokens}${card.usage.reasoningTokens !== null ? ` (reasoning ${card.usage.reasoningTokens})` : ''}`}
        </p>
      )}
    </article>
  );
}
